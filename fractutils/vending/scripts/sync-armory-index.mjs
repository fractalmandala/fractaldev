#!/usr/bin/env node
// sync-armory-index.mjs — regenerate armory/skills/INDEX.md from what is actually
// on disk. The previous index claimed 174 skills while 23 were bundled; every
// missing row was a dead link an agent could follow. Generating the index removes
// that failure mode instead of asking humans to remember.
//
//   node scripts/sync-armory-index.mjs          write
//   node scripts/sync-armory-index.mjs --check   exit 1 if stale (CI / prepublish)

import { readFileSync, writeFileSync, readdirSync, existsSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const SKILLS = join(ROOT, 'armory', 'skills');
const INDEX = join(SKILLS, 'INDEX.md');
const ROUTING = join(ROOT, 'armory', 'routing.json');

function description(dir) {
	const raw = readFileSync(join(SKILLS, dir, 'SKILL.md'), 'utf8');
	const fm = raw.match(/^---\n([\s\S]*?)\n---/);
	if (!fm) return '';
	const block = fm[1];
	const m = block.match(/^description:\s*(.*)$/m);
	if (!m) return '';
	let d = m[1].trim();
	if (['>', '>-', '|', '|-'].includes(d)) {
		const after = block.slice(block.indexOf(m[0]) + m[0].length);
		d = [];
		for (const line of after.split('\n')) {
			if (/^\s+\S/.test(line)) d.push(line.trim());
			else if (d.length) break;
		}
		d = d.join(' ');
	}
	return d.replace(/^['"]|['"]$/g, '').replace(/\s+/g, ' ').trim();
}

const skills = readdirSync(SKILLS, { withFileTypes: true })
	.filter((d) => d.isDirectory() && existsSync(join(SKILLS, d.name, 'SKILL.md')))
	.map((d) => d.name)
	.sort();

const routing = JSON.parse(readFileSync(ROUTING, 'utf8'));

const supersededBy = new Map();
for (const rule of routing.skillPrecedence) {
	for (const s of rule.supersedes) supersededBy.set(s, rule.canonical);
}

const routedFrom = new Map();
for (const r of [...routing.routes, routing.fallback]) {
	const tag = (s, kind) => {
		if (!routedFrom.has(s)) routedFrom.set(s, new Set());
		routedFrom.get(s).add(`${r.id}:${kind}`);
	};
	tag(r.entrySkill, 'entry');
	for (const s of r.required) tag(s, 'required');
	for (const c of r.conditional ?? []) for (const s of c.skills) tag(s, 'conditional');
}

const rows = skills.map((s) => {
	const routes = routedFrom.get(s);
	const status = supersededBy.has(s)
		? `superseded by \`${supersededBy.get(s)}\``
		: routes
			? [...routes].map((r) => r.split(':')[0]).filter((v, i, a) => a.indexOf(v) === i).join(', ')
			: '**orphan**';
	const d = description(s);
	return `| [\`${s}\`](./${s}/) | ${status} | ${d.slice(0, 180)} |`;
});

const body = `# Skills Index

<!-- GENERATED by scripts/sync-armory-index.mjs — do not edit by hand. -->
<!-- Run: node scripts/sync-armory-index.mjs -->

Live inventory of \`skills/\`, generated from disk. Every row below exists.

**Current entries:** ${skills.length}

Prefer the CLI over this table — it resolves precedence for you:

\`\`\`sh
fa skill --list
fa route "<your task>"
\`\`\`

The **Routed from** column shows which \`routing.json\` routes reach a skill. A skill
marked *superseded* is bundled for a narrow case only; load its canonical instead.
An **orphan** is bundled but unreachable from any route — either route it or drop it.

| Skill | Routed from | Description |
| --- | --- | --- |
${rows.join('\n')}
`;

const current = existsSync(INDEX) ? readFileSync(INDEX, 'utf8') : '';

if (process.argv.includes('--check')) {
	if (current !== body) {
		console.error('armory/skills/INDEX.md is stale. Run: node scripts/sync-armory-index.mjs');
		process.exit(1);
	}
	console.log(`skills index up to date (${skills.length} entries)`);
	process.exit(0);
}

writeFileSync(INDEX, body);
console.log(`wrote armory/skills/INDEX.md — ${skills.length} skills, ${supersededBy.size} superseded`);
