import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const packageDir = path.resolve(__dirname, '..');

// Vendored upstream SVGs live outside src/lib so svelte-package never copies
// them into dist (they are build inputs, not published files).
const sourceDir = path.join(packageDir, 'vendor/icons');
const libDir = path.join(packageDir, 'src/lib');
const lockPath = path.join(packageDir, '.generate-icons.lock');
const packageTempDir = path.join(packageDir, '.svelte-kit/__package__');

const generatedHeader = '// Generated by scripts/generate-icons.js. Do not edit by hand.\n';
const hardcodedCurrentColorCandidates = [
	'#000',
	'#000000',
	'#0f172a',
	'#111',
	'#111111',
	'#1f2937',
	'black',
	'rgb(0,0,0)',
	'rgb(0, 0, 0)'
];

const presentationAttrNames = [
	'fill',
	'stroke',
	'stroke-width',
	'stroke-linecap',
	'stroke-linejoin',
	'stroke-miterlimit',
	'stroke-dasharray',
	'stroke-dashoffset',
	'stroke-opacity',
	'fill-rule',
	'fill-opacity',
	'clip-rule'
];

export const familyPrefixMap = {
	anticons: 'an',
	boxregular: 'bx',
	boxsolid: 'bxs',
	circum: 'ci',
	coreui: 'cu',
	cssgg: 'gg',
	famicons: 'fa',
	feathericons: 'fe',
	fontawesome: 'far',
	fontawesomesolid: 'fas',
	heroicons: 'he',
	heroiconsfill: 'hef',
	iconoir: 'ic',
	iconoirfill: 'icf',
	lucide: 'lu',
	materialanim: 'maa',
	octicons: 'oc',
	phosphor: 'ph',
	phosphorfill: 'phf',
	remix: 're',
	remixfill: 'ref',
	simple: 'si',
	simpleline: 'sl',
	tabler: 'tb',
	tablerfill: 'tbf'
};

function safeRemove(targetPath) {
	if (fs.existsSync(targetPath)) {
		fs.rmSync(targetPath, { recursive: true, force: true, maxRetries: 10, retryDelay: 50 });
	}
}

function getPrefix(setName) {
	return familyPrefixMap[setName] || setName;
}

export function toIdentifierPart(value) {
	return value
		.split(/[^a-zA-Z0-9]+/)
		.filter(Boolean)
		.map((part) => part.charAt(0).toUpperCase() + part.slice(1))
		.join('');
}

export function toNamedExport(setName, iconName) {
	const prefix = getPrefix(setName);
	const name = `${prefix}-${iconName}`;
	const identifier = name.charAt(0).toLowerCase() + toIdentifierPart(name).slice(1);

	return /^[0-9]/.test(identifier) ? `icon${identifier}` : identifier;
}

export function toFullNameExport(setName, iconName) {
	const name = `${setName}-${iconName}`;
	const identifier = name.charAt(0).toLowerCase() + toIdentifierPart(name).slice(1);

	return /^[0-9]/.test(identifier) ? `icon${identifier}` : identifier;
}

export function toSafePathName(filename) {
	return filename.replace(/\.svg$/i, '').toLowerCase();
}

export function extractViewBox(svg) {
	const vbMatch = svg.match(/<svg[^>]*\bviewBox="([^"]+)"/i);
	if (vbMatch) return vbMatch[1];

	const widthMatch = svg.match(/<svg[^>]*\bwidth="([0-9.]+)(?:px)?"/i);
	const heightMatch = svg.match(/<svg[^>]*\bheight="([0-9.]+)(?:px)?"/i);
	if (widthMatch && heightMatch) {
		return `0 0 ${widthMatch[1]} ${heightMatch[1]}`;
	}

	return '0 0 24 24';
}

function escapeRegExp(value) {
	return value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

export function normalizeColor(svg) {
	let result = svg;

	// Case-insensitive: upstream sets mix `#0F172A` and `#0f172a` for the same black.
	// Whitespace after the CSS colon is deliberately NOT tolerated: `fill: #000` inside a
	// <mask> (materialanim) is mask geometry, not a color, and must stay black.
	for (const color of hardcodedCurrentColorCandidates) {
		const pattern = escapeRegExp(color);

		result = result
			.replace(new RegExp(`fill="${pattern}"`, 'gi'), 'fill="currentColor"')
			.replace(new RegExp(`stroke="${pattern}"`, 'gi'), 'stroke="currentColor"')
			.replace(new RegExp(`fill:${pattern}`, 'gi'), 'fill:currentColor')
			.replace(new RegExp(`stroke:${pattern}`, 'gi'), 'stroke:currentColor');
	}

	return result;
}

export function stripSvg(svg) {
	const svgTagMatch = svg.match(/<svg\b([^>]*)>/i);
	const rootAttrs = svgTagMatch ? svgTagMatch[1] : '';

	const collectedAttrs = [];
	for (const attr of presentationAttrNames) {
		const match = rootAttrs.match(new RegExp(`\\b${attr}="([^"]*)"`, 'i'));
		if (match) {
			collectedAttrs.push(`${attr}="${match[1]}"`);
		}
	}

	// Remove XML declarations, DOCTYPEs, and comments
	let cleaned = svg
		.replace(/<\?xml[^>]*\?>/gi, '')
		.replace(/<!DOCTYPE[^>]*>/gi, '')
		.replace(/<!--[\s\S]*?-->/g, '');

	// Drop upstream metadata elements (Simple Icons ships a <title> in every file);
	// Icon.svelte owns the accessible name via its own `title` prop.
	cleaned = cleaned
		.replace(/<title\b[^>]*>[\s\S]*?<\/title>/gi, '')
		.replace(/<desc\b[^>]*>[\s\S]*?<\/desc>/gi, '');

	// Strip outer <svg ...> and </svg>
	cleaned = cleaned.replace(/^[\s\S]*?<svg[^>]*>/i, '').replace(/<\/svg>[\s\S]*$/i, '');

	// Remove invisible spacer rects (fill="none" with no stroke)
	cleaned = cleaned.replace(
		/<rect\b(?![^>]*\bstroke=)[^>]*\bfill="none"[^>]*\/?>(\s*<\/rect>)?/gi,
		''
	);

	let inner = normalizeColor(cleaned.trim());

	// If root <svg> had presentation attributes (e.g. fill="none" stroke="currentColor" stroke-width="2"),
	// wrap in a <g> tag to preserve stroke/fill styling
	if (collectedAttrs.length > 0) {
		const attrStr = normalizeColor(collectedAttrs.join(' '));
		inner = `<g ${attrStr}>${inner}</g>`;
	}

	return inner;
}

function cleanGeneratedSet(setName) {
	// Remove the legacy per-icon directory (pre-0.3.0 layout) and the
	// single-file module, which is rewritten below.
	safeRemove(path.join(libDir, setName));
	safeRemove(path.join(libDir, `${setName}.ts`));
}

export function toIconDeclaration(setName, iconName, svg) {
	const exportName = toNamedExport(setName, iconName);
	const fullAliasName = toFullNameExport(setName, iconName);
	const viewBox = extractViewBox(svg);
	const body = stripSvg(svg);

	// Compact JSON + an explicit IconData annotation (instead of `as const`):
	// keeps the emitted JS small and collapses the .d.ts to a short
	// declaration instead of a full string-literal type per icon.
	const data = JSON.stringify({ name: iconName, set: setName, viewBox, body });
	let declaration = `export const ${exportName}: IconData = ${data};`;
	if (fullAliasName !== exportName) {
		declaration += `\nexport { ${exportName} as ${fullAliasName} };`;
	}

	return { exportName, fullAliasName, iconName, declaration };
}

let duplicateCount = 0;

function writeSetModule(setName, icons) {
	// One self-contained module per family. Bundlers drop unused top-level
	// statements, so named imports shake out to just the icons referenced —
	// with one file resolution per family instead of thousands.
	const seen = new Set();
	const lines = [];
	for (const icon of icons) {
		if (seen.has(icon.exportName)) {
			console.error(`${setName}: DUPLICATE export ${icon.exportName} — keeping first`);
			duplicateCount++;
			continue;
		}
		seen.add(icon.exportName);
		lines.push(icon.declaration);
	}

	fs.writeFileSync(
		path.join(libDir, `${setName}.ts`),
		`${generatedHeader}import type { IconData } from './types.js';\n\n${lines.join('\n')}\n`,
		'utf8'
	);

	return lines.length;
}

// Main guard: only run generation when executed directly, not when imported for tests.
const isMain = process.argv[1] && fileURLToPath(import.meta.url).endsWith(process.argv[1].replace(/\\/g, '/'));

if (isMain) {
	if (!fs.existsSync(sourceDir)) {
		console.log(`No icons directory found at ${sourceDir}`);
		process.exit(0);
	}

	try {
		fs.writeFileSync(lockPath, String(process.pid), { flag: 'wx' });
	} catch {
		console.error('Icon generation is already running.');
		process.exit(1);
	}

	// Clean any leftover build cache to prevent ENOTEMPTY in @sveltejs/package
	safeRemove(packageTempDir);

	const startTime = Date.now();
	const setNames = fs
		.readdirSync(sourceDir, { withFileTypes: true })
		.filter((entry) => entry.isDirectory())
		.map((entry) => entry.name)
		.sort();

	let totalIcons = 0;
	let totalSets = 0;

	try {
		for (const setName of setNames) {
			const setSourceDir = path.join(sourceDir, setName);
			const svgFiles = fs
				.readdirSync(setSourceDir, { withFileTypes: true })
				.filter((entry) => entry.isFile() && entry.name.endsWith('.svg'))
				.map((entry) => entry.name)
				.sort();

			if (svgFiles.length === 0) {
				console.log(`${setName}: skipped (0 SVGs found)`);
				continue;
			}

			cleanGeneratedSet(setName);

			const icons = svgFiles.map((file) => {
				const iconName = toSafePathName(file);
				const svg = fs.readFileSync(path.join(setSourceDir, file), 'utf8');

				return toIconDeclaration(setName, iconName, svg);
			});

			const emitted = writeSetModule(setName, icons);
			totalIcons += emitted;
			totalSets++;
			console.log(`${setName} (${getPrefix(setName)}): generated ${emitted} icons`);
		}

		// Pre-clean .svelte-kit/__package__ so svelte-package never hits ENOTEMPTY on macOS APFS
		safeRemove(packageTempDir);

		const elapsed = ((Date.now() - startTime) / 1000).toFixed(2);
		console.log(
			`\nSuccessfully generated ${totalIcons} icons across ${totalSets} sets in ${elapsed}s.`
		);

		if (duplicateCount > 0) {
			console.error(
				`${duplicateCount} duplicate(s) found — investigate upstream naming collisions.`
			);
			process.exitCode = 1;
		}
	} finally {
		fs.rmSync(lockPath, { force: true });
	}
}
